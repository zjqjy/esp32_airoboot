#!/usr/bin/env python3
"""anim2lvgl.py — 现有 4bpp 素材 (cat_assets.c) → LVGL v9 RGB565 C 数组 (cat_lvgl_assets.c)

S4-B 交付物：LVGL 显示栈素材管线。
数据源直接解析 cat_assets.c（S3 已上板验证的 4bpp+调色板数据），不重跑 GIF 烘焙，
保证与现网素材逐像素一致。

为什么是 RGB565 而不是 I4（索引色）:
    LVGL v9 软渲染下，索引图打开时会整图转换成 ARGB8888 缓冲
    (bin_decoder: "Convert to ARGB8888, since sw renderer cannot render it directly"),
    220x220 一帧 ≈ 194KB 堆内存，无 PSRAM 扛不住。
    RGB565 C 数组走 lv_draw_buf_from_image 零拷贝路径，解码器直接指向 flash 常量,
    零 RAM / 零转换 CPU；代价是 flash 4x（3.57M 像素 ≈ 7.1MB，16MB 分区装得下）。

用法:
    python tools/anim2lvgl.py [--src main/cat/cat_assets.c] [--outdir main/cat] [--checkdir]

输出:
    <outdir>/cat_lvgl_assets.h  — cat_anim_lvgl_t 结构 + extern 声明
    <outdir>/cat_lvgl_assets.c  — 逐帧 lv_image_dsc_t (RGB565)
    --checkdir 时: 回读生成的 C 文件逐像素比对 + 输出 PNG 目检图
"""

import argparse
import re
import sys
from pathlib import Path

HEADER_NAME = "cat_lvgl_assets"


def parse_assets(src: Path) -> list:
    """解析 anim_gif2c.py 生成的 cat_assets.c。返回 anim 字典列表。"""
    text = src.read_text(encoding="utf-8")

    structs = re.findall(r"const cat_anim_t (\w+) = \{(.*?)\};", text, re.DOTALL)
    if not structs:
        sys.exit(f"{src} 里没找到 cat_anim_t 结构")

    idx_arrays = {}  # (prefix, k) -> bytes
    for m in re.finditer(r"static const uint8_t (\w+)_idx(\d+)\[\] = \{([0-9a-fA-Fx, ]*)\}", text):
        idx_arrays[(m.group(1), int(m.group(2)))] = bytes(
            int(v, 16) for v in m.group(3).replace("\n", " ").split(",") if v.strip()
        )
    dur_arrays = {}
    for m in re.finditer(r"static const uint16_t (\w+)_dur\[\d+\] = \{([^}]*)\}", text):
        dur_arrays[m.group(1)] = [int(v) for v in m.group(2).split(",") if v.strip()]

    anims = []
    for name, body in structs:
        w = int(re.search(r"\.w = (\d+)", body).group(1))
        h = int(re.search(r"\.h = (\d+)", body).group(1))
        n = int(re.search(r"\.n_frames = (\d+)", body).group(1))
        bg = int(re.search(r"\.bg_color = 0x([0-9A-Fa-f]+)", body).group(1), 16)
        prefix = re.search(r"\.palette = (\w+)_pal", body).group(1)

        pal = re.search(rf"static const uint16_t {prefix}_pal\[16\] = \{{([^}}]*)\}}", text).group(1)
        palette = [int(v, 16) for v in pal.split(",") if v.strip()]
        frames = [idx_arrays[(prefix, k)] for k in range(n)]
        delays = dur_arrays[prefix]
        anims.append(dict(name=name, w=w, h=h, n=n, bg=bg, palette=palette,
                          frames=frames, delays=delays, prefix=prefix))
    return anims


def expand_4bpp(a: dict) -> list:
    """4bpp 帧 + 调色板 → 每帧 uint16 RGB565 列表（与设备端旧渲染同一路径展开）。"""
    out = []
    row_bytes = (a["w"] + 1) // 2
    for ib in a["frames"]:
        px = []
        for i in range(a["w"] * a["h"]):
            b = ib[i >> 1]
            px.append(a["palette"][(b >> 4) if not (i & 1) else (b & 0xF)])
        assert len(ib) == row_bytes * a["h"], f"{a['name']} 帧 {len(ib)}B != {row_bytes}*{a['h']}"
        out.append(px)
    return out


def emit_c(anims, outdir: Path):
    h_path = outdir / f"{HEADER_NAME}.h"
    c_path = outdir / f"{HEADER_NAME}.c"

    h = [
        "#pragma once",
        "// Generated by tools/anim2lvgl.py — DO NOT EDIT",
        "// 素材源: cat_assets.c (S3 烘焙数据) → LVGL v9 RGB565 零拷贝图像",
        '#include "lvgl.h"',
        "",
        "typedef struct {",
        "    const char *name;",
        "    uint16_t w, h, n_frames;",
        "    uint16_t bg_color;                      /* RGB565, 屏幕底色 */",
        "    const lv_image_dsc_t *const *frames;    /* 逐帧图像描述符 */",
        "    const uint16_t *delay_ms;               /* 逐帧 GIF 时序 */",
        "} cat_anim_lvgl_t;",
        "",
    ]
    h += [f"extern const cat_anim_lvgl_t {a['name']};" for a in anims]
    h_path.write_text("\n".join(h) + "\n", encoding="utf-8")

    c = [
        "// Generated by tools/anim2lvgl.py — DO NOT EDIT",
        f"// RGB565 帧数据合计: {sum(a['w'] * a['h'] * 2 * a['n'] for a in anims) // 1024}KB",
        f'#include "{HEADER_NAME}.h"',
        "",
    ]
    for a in anims:
        p = a["prefix"]
        n_px = a["w"] * a["h"]
        stride = a["w"] * 2
        for k, px in enumerate(a["expanded"]):
            c.append(f"static const uint16_t {p}_f{k}[{n_px}] = {{")
            for i in range(0, n_px, 12):
                c.append("    " + ", ".join(f"0x{v:04X}" for v in px[i:i + 12]) + ",")
            c.append("};")
        for k in range(a["n"]):
            c += [
                f"static const lv_image_dsc_t {p}_img{k} = {{",
                "    .header = {",
                f"        .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_RGB565,",
                f"        .w = {a['w']}, .h = {a['h']}, .stride = {stride},",
                "    },",
                f"    .data_size = {n_px} * 2,",
                f"    .data = (const uint8_t *){p}_f{k},",
                "};",
            ]
        c.append(
            f"static const lv_image_dsc_t *const {p}_frames[{a['n']}] = "
            "{" + ", ".join(f"&{p}_img{k}" for k in range(a["n"])) + "};"
        )
        c.append(f"static const uint16_t {p}_dur[{a['n']}] = " +
                 "{" + ", ".join(map(str, a["delays"])) + "};")
        c += [
            f"const cat_anim_lvgl_t {a['name']} = {{",
            f'    .name = "{a["name"]}", .w = {a["w"]}, .h = {a["h"]}, '
            f".n_frames = {a['n']}, .bg_color = 0x{a['bg']:04X},",
            f"    .frames = {p}_frames, .delay_ms = {p}_dur,",
            "};",
            "",
        ]
    c_path.write_text("\n".join(c) + "\n", encoding="utf-8")
    print(f"写出 {c_path} ({c_path.stat().st_size // 1024}KB) / {h_path}")


def verify(anims, outdir: Path, checkdir: Path | None):
    """回读生成的 C 文件, 逐像素比对 4bpp 参考路径; 可选输出 PNG 目检图。"""
    text = (outdir / f"{HEADER_NAME}.c").read_text(encoding="utf-8")

    def array_of(sym: str) -> list:
        body = re.search(rf"static const uint16_t {sym}\[\d+\] = \{{(.*?)\}};", text, re.DOTALL).group(1)
        return [int(v, 16) for v in re.findall(r"0x([0-9A-Fa-f]{4})", body)]

    ok_all = True
    for a in anims:
        p = a["prefix"]
        n_px = a["w"] * a["h"]
        ref_rows, got_rows = a["expanded"], []
        for k in range(a["n"]):
            got_rows.append(array_of(f"{p}_f{k}"))
        mism = sum(1 for r_ref, r_got in zip(ref_rows, got_rows)
                   for x, y in zip(r_ref, r_got) if x != y)
        total = a["n"] * n_px
        ok = mism == 0 and all(len(r) == n_px for r in got_rows)
        ok_all &= ok
        print(f"[{'PASS' if ok else 'FAIL'}] {a['name']}: {total} 像素 x {a['n']} 帧, 差异 {mism}")

        if checkdir:
            from PIL import Image
            cols, cell = 6, 160
            rows = (a["n"] + cols - 1) // cols
            sheet = Image.new("RGB", (cell * cols + 8, cell * rows + 8), (255, 0, 255))
            for k, row in enumerate(got_rows):
                img = Image.new("RGB", (a["w"], a["h"]))
                img.putdata([((v >> 8) & 0xF8, (v >> 3) & 0xFC, (v << 3) & 0xF8) for v in row])
                t = img.copy(); t.thumbnail((cell - 8, cell - 8))
                sheet.paste(t, ((k % cols) * cell + 4, (k // cols) * cell + 4))
            sheet.save(checkdir / f"{a['name']}_lvgl_check.png")
    return ok_all


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", default="main/cat/cat_assets.c")
    ap.add_argument("--outdir", default="main/cat")
    ap.add_argument("--checkdir", default=None, help="输出逐像素比对 PNG 的目录 (需 PIL)")
    args = ap.parse_args()

    anims = parse_assets(Path(args.src))
    for a in anims:
        a["expanded"] = expand_4bpp(a)
        print(f"[{a['name']}] {a['w']}x{a['h']} {a['n']}帧 "
              f"数据={a['n'] * a['w'] * a['h'] * 2 // 1024}KB bg=0x{a['bg']:04X}")
    emit_c(anims, Path(args.outdir))
    checkdir = Path(args.checkdir) if args.checkdir else None
    if checkdir:
        checkdir.mkdir(parents=True, exist_ok=True)
    if not verify(anims, Path(args.outdir), checkdir):
        sys.exit("逐像素比对失败")


if __name__ == "__main__":
    main()
